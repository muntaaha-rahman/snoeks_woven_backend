def normalize_lang(lang: str | None) -> str:
    return lang if lang in SUPPORTED else DEFAULT_LANG


def translator(lang: str | None):
    lang = normalize_lang(lang)

    def t(key: str, **params: str) -> str:
        text = _STRINGS[lang][key]
        return text.format(**params) if params else text

    return t


def value_translator(lang: str | None):
    lang = normalize_lang(lang)

    def v(value, prefix: str = "") -> str:
        if not value:
            return ""
        return _VALUES[lang].get(f"{prefix}{value}", str(value))

    return v
